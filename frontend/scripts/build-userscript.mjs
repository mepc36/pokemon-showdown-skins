import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {ShowdownSessionAuth} from '../src/session-upkeep.mjs';
import {installControllerLauncher} from '../src/userscript-launcher.mjs';

// Development convenience only: the small installable file is checked in.
// No Vite build, app bundle, artifact download or deployment is needed to install.
const path = fileURLToPath(new URL('../../skins/controller-client/controller-client.user.js', import.meta.url));
const source = `// ==UserScript==
// @name         Showdown Independent Controller (prototype)
// @namespace    https://github.com/mepc36/pokemon-showdown-skins
// @version      0.3.0
// @description  Open the hosted controller UI and use your existing Showdown session to sign in.
// @match        https://play.pokemonshowdown.com/*
// @run-at       document-idle
// @noframes
// @grant        none
// ==/UserScript==

// Source: frontend/src/{userscript-launcher.mjs,session-upkeep.mjs}.
// Generated by npm run build:userscript. Download and install this file directly.
(() => {
'use strict';
${ShowdownSessionAuth.toString()}
${installControllerLauncher.toString()}
installControllerLauncher();
})();
`;
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== source) throw new Error('Run npm run build:userscript and commit the updated small userscript.');
} else await writeFile(path, source);
console.log(`controller-client.user.js: ${(Buffer.byteLength(source) / 1024).toFixed(1)} KiB; hosted UI is not bundled.`);
